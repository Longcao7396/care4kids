// Stats shape consumed by OurPartnersPage header. Built from
// SAMPLE_ORGANIZATIONS so fallback and live API stats render identically.
export const buildSampleStats = (orgs = SAMPLE_ORGANIZATIONS) => ({
  total: orgs.length,
  supporters: orgs.filter((o) => o.organizationType === 'Supporter').length,
  partners: orgs.filter((o) => o.organizationType === 'Partner').length,
  ngos: orgs.filter((o) => o.organizationType === 'NGO').length,
  totalContribution: orgs.reduce((sum, o) => sum + (o.contributionAmount || 0), 0)
});
